/// 아레나 모드에서 웨이브를 클리어할 때마다 3장 중 1장을 고르는 강화 카드.
///
/// 로그라이트("서바이버라이크")의 재미는 **매 판 다른 조합**에서 나온다. 그래서
/// 카드 풀을 5종으로 두고 클리어마다 무작위 3장을 뽑아 제시한다 — 매번 같은
/// 3장이면 두 번째 판부터는 고르는 재미가 사라진다.
///
/// 효과 지속 범위가 카드마다 다르다:
/// - [heal] — 즉시 1회 적용(하트 회복).
/// - [shield] — 쓸 때까지 유지(오답 1회 무효).
/// - 나머지 — **다음 웨이브 한 판만** 적용. 영구 버프로 두면 후반 웨이브가
///   너무 쉬워져 난이도 곡선이 무너진다.
enum ArenaUpgrade {
  doubleScore('⚡', '점수 2배', '다음 웨이브 점수가 두 배!'),
  heal('❤️', '하트 회복', '하트를 하나 채워요'),
  extraTime('⏱️', '시간 +5초', '다음 웨이브를 5초 더!'),
  shield('🛡️', '방어막', '틀려도 한 번은 안전해요'),
  fewerChoices('🎯', '보기 줄이기', '다음 웨이브는 보기가 2개!');

  const ArenaUpgrade(this.emoji, this.title, this.description);

  final String emoji;
  final String title;
  final String description;
}
